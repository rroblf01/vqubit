"""OpenQASM 2.0 export.

:func:`qasm` turns a circuit (or a single operation) into OpenQASM 2.0 text.
Gates that have no native QASM instruction are expanded through their
decomposition, so a Toffoli comes out as the ``ccx`` it maps to and a Fredkin as
the CNOT/Toffoli/CNOT sequence it decomposes into.
"""

from __future__ import annotations

import math
import re
from typing import Any

from ._circuits import Circuit
from ._control_values import AbstractControlValues
from ._gates import (
	CCXGate,
	CNOTGate,
	ControlledGate,
	CZGate,
	HPowGate,
	IdentityGate,
	MeasurementGate,
	RxGate,
	RyGate,
	RzGate,
	SWAPGate,
	XPowGate,
	YPowGate,
	ZPowGate,
	is_plain_gate,
)
from ._ops import GateOperation, Operation
from ._parameter import is_symbolic
from ._qubits import Qid

_HEADER = ["// Generated by vqubit", "OPENQASM 2.0;", 'include "qelib1.inc";']


def _plain_control_values(gate: Any) -> bool:
	"""Whether a gate's controls are the plain all-ones kind.

	A control-value *formula* has no "all values are true" reading, so it is not
	a plain CNOT/CZ.
	"""
	values = gate.control_values
	if isinstance(values, AbstractControlValues):
		return False
	return all(values)


def _format_angle(value: Any) -> str:
	if is_symbolic(value):
		return str(value)
	number = float(value)
	if number == int(number):
		return str(int(number))
	return repr(number)


def _gate_instruction(gate: Any, qubits: list[str]) -> str | None:
	"""Return a single QASM instruction for ``gate``, or ``None`` if unknown."""
	if isinstance(gate, MeasurementGate):
		return None  # measurements are handled separately
	if isinstance(gate, XPowGate):
		if gate.exponent == 1:
			return f"x {qubits[0]};"
		return f"rx({_format_angle(math.pi * gate.exponent)}) {qubits[0]};"
	if isinstance(gate, YPowGate):
		if gate.exponent == 1:
			return f"y {qubits[0]};"
		return f"ry({_format_angle(math.pi * gate.exponent)}) {qubits[0]};"
	if isinstance(gate, ZPowGate):
		table = {1: "z", 0.5: "s", 0.25: "t", -0.5: "sdg", -0.25: "tdg"}
		if gate.exponent in table:
			return f"{table[gate.exponent]} {qubits[0]};"
		return f"rz({_format_angle(math.pi * gate.exponent)}) {qubits[0]};"
	if isinstance(gate, HPowGate):
		if gate.exponent == 1:
			return f"h {qubits[0]};"
		return None
	if isinstance(gate, IdentityGate):
		return f"id {qubits[0]};"
	if isinstance(gate, RxGate):
		return f"rx({_format_angle(gate.radians)}) {qubits[0]};"
	if isinstance(gate, RyGate):
		return f"ry({_format_angle(gate.radians)}) {qubits[0]};"
	if isinstance(gate, RzGate):
		return f"rz({_format_angle(gate.radians)}) {qubits[0]};"
	if isinstance(gate, CNOTGate) and is_plain_gate(gate):
		return f"cx {qubits[0]},{qubits[1]};"
	if isinstance(gate, CZGate) and is_plain_gate(gate):
		return f"cz {qubits[0]},{qubits[1]};"
	if isinstance(gate, SWAPGate) and is_plain_gate(gate):
		return f"swap {qubits[0]},{qubits[1]};"
	if isinstance(gate, CCXGate) and is_plain_gate(gate):
		return f"ccx {qubits[0]},{qubits[1]},{qubits[2]};"
	if (
		isinstance(gate, ControlledGate)
		and isinstance(gate.sub_gate, XPowGate)
		and gate.sub_gate.exponent == 1
		and _plain_control_values(gate)
	):
		target = qubits[-1]
		controls = qubits[:-1]
		if len(controls) == 1:
			return f"cx {controls[0]},{target};"
		if len(controls) == 2:
			return f"ccx {controls[0]},{controls[1]},{target};"
	return None


def _operation_lines(operation: Operation, qubit_ids: dict[Qid, str], indent: str) -> list[str]:
	gate = operation.gate
	qubits = [qubit_ids[q] for q in operation.qubits]

	if isinstance(gate, MeasurementGate):
		register = _register_name(gate.key)
		return [f"{indent}measure {qubits[i]} -> {register}[{i}];" for i in range(len(qubits))]

	instruction = _gate_instruction(gate, qubits)
	if instruction is not None:
		return [indent + instruction]

	expanded = gate._decompose_(operation.qubits)
	if expanded is not None:
		lines: list[str] = []
		for child in expanded:
			lines.extend(_operation_lines(child, qubit_ids, indent))
		return lines

	raise TypeError(f"{gate!r} cannot be written as OpenQASM 2.0")


_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def _register_name(key: str) -> str:
	"""The classical register for a measurement key.

	The key is used verbatim so that import/export round-trips, which needs it to
	be a valid OpenQASM identifier.
	"""
	if not _IDENTIFIER.match(key):
		raise ValueError(f"the measurement key {key!r} is not a valid OpenQASM identifier")
	return key


def _measurement_register_sizes(operations: list[Operation]) -> dict[str, int]:
	sizes: dict[str, int] = {}
	for operation in operations:
		if isinstance(operation.gate, MeasurementGate):
			key = operation.gate.key
			sizes[key] = max(sizes.get(key, 0), len(operation.qubits))
	return sizes


def qasm(value: Any) -> str:
	"""Return the OpenQASM 2.0 representation of ``value``.

	>>> import vqubit
	>>> q0 = vqubit.LineQubit(0)
	>>> vqubit.qasm(vqubit.Circuit(vqubit.X(q0))).splitlines()[-1]
	'x q[0];'
	"""
	if isinstance(value, Circuit):
		operations = list(value.all_operations())
		qubits = value.all_qubits()
		write_header = True
	elif isinstance(value, (GateOperation, Operation)):
		operations = [value]
		qubits = tuple(sorted(set(value.qubits)))
		write_header = False
	else:
		raise TypeError(f"cannot convert {value!r} to QASM")

	qubit_ids = {q: f"q[{i}]" for i, q in enumerate(qubits)}

	lines: list[str] = []
	if write_header:
		lines.extend(_HEADER)
		lines.append(f"qreg q[{len(qubits)}];")
		for key, size in _measurement_register_sizes(operations).items():
			lines.append(f"creg {_register_name(key)}[{size}];")

	for operation in operations:
		lines.extend(_operation_lines(operation, qubit_ids, ""))
	return "\n".join(lines)


class QasmArgs:
	"""The context passed to a gate's QASM writer.

	Mirrors Cirq's ``QasmArgs``: it maps qubits to the names QASM uses and
	carries the precision and the free arguments.
	"""

	def __init__(
		self,
		*,
		qubit_id_map: Any = None,
		precision: int = 15,
		version: str = "2.0",
		args: Any = None,
	) -> None:
		self.qubit_id_map = dict(qubit_id_map or {})
		self.precision = int(precision)
		self.version = version
		self.args = dict(args or {})

	def format(self, text: str) -> str:
		"""Return ``text`` unchanged (the writer already formatted it)."""
		return text

	def __repr__(self) -> str:
		return f"vqubit.QasmArgs(version={self.version!r})"


__all__ = ["QasmArgs", "qasm"]
